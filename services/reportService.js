const PDFDocument = require('pdfkit');
const QRCode = require('qrcode');
const crypto = require('crypto');
const Report = require('../models/Report');

/**
 * Generates a unique, sequential report ID in the format SLR-YYYY-NNNNNN
 */
async function generateReportId() {
  const year = new Date().getFullYear();
  const count = await Report.countDocuments({ reportId: new RegExp(`^SLR-${year}-`) });
  const sequence = String(count + 1).padStart(6, '0');
  return `SLR-${year}-${sequence}`;
}

/**
 * Generates a SHA-256 hash of the report's source data for integrity
 * verification. Deterministic — same input always produces the same hash.
 */
function generateReportHash({ applicationId, prediction, probability, modelVersion, generatedAt }) {
  const payload = JSON.stringify({ applicationId, prediction, probability, modelVersion, generatedAt: generatedAt.toISOString() });
  return crypto.createHash('sha256').update(payload).digest('hex');
}

/**
 * Creates and persists Report metadata, returns the report record.
 * Called once per report generation — the PDF then embeds this reportId.
 */
async function createReportRecord({ application, prediction, user }) {
  const reportId = await generateReportId();
  const generatedAt = new Date();

  const reportHash = generateReportHash({
    applicationId: application.applicationId,
    prediction: prediction.prediction,
    probability: prediction.probability,
    modelVersion: prediction.modelVersion,
    generatedAt
  });

  const report = await Report.create({
    reportId,
    application: application._id,
    prediction: prediction._id,
    user: user._id,
    modelVersion: prediction.modelVersion,
    reportHash,
    generatedAt
  });

  return report;
}

/**
 * Generates the full 4-page professional PDF report and streams it
 * directly to the response.
 */
async function generateReportPDF(res, { application, prediction, report, baseUrl }) {
  const doc = new PDFDocument({ margin: 50, size: 'A4' });

  res.setHeader('Content-Type', 'application/pdf');
  res.setHeader('Content-Disposition', `attachment; filename=SmartLoanAI_${application.applicationId}.pdf`);
  doc.pipe(res);

  const verifyUrl = `${baseUrl}/verify/${report.reportId}`;
  const qrDataUrl = await QRCode.toDataURL(verifyUrl, { margin: 1, width: 160 });
  const qrBuffer = Buffer.from(qrDataUrl.split(',')[1], 'base64');

  const COLOR_PRIMARY = '#2563EB';
  const COLOR_SECONDARY = '#7C3AED';
  const COLOR_MUTED = '#64748B';
  const COLOR_TEXT = '#0F172A';
  const COLOR_BORDER = '#E2E8F0';

  function sectionDivider() {
    doc.strokeColor(COLOR_BORDER).moveTo(50, doc.y).lineTo(545, doc.y).stroke();
    doc.moveDown();
  }

  function sectionHeading(text) {
    doc.fontSize(13).fillColor(COLOR_SECONDARY).text(text);
    doc.moveDown(0.5);
  }

  function kvRow(label, value) {
    doc.fontSize(10).fillColor(COLOR_MUTED).text(label, { continued: true });
    doc.fillColor(COLOR_TEXT).text(`  ${value}`);
  }

  // ============ PAGE 1 — COVER ============
  doc.fontSize(24).fillColor(COLOR_PRIMARY).text('SMARTLOAN AI', { align: 'center' });
  doc.fontSize(14).fillColor(COLOR_MUTED).text('Loan Eligibility Analysis Report', { align: 'center' });
  doc.moveDown(2);

  doc.rect(50, doc.y, 495, 160).strokeColor(COLOR_BORDER).stroke();
  const boxTop = doc.y + 20;
  doc.fontSize(11).fillColor(COLOR_TEXT);
  doc.text(`Application ID:  ${application.applicationId}`, 70, boxTop);
  doc.text(`Report ID:  ${report.reportId}`, 70, boxTop + 25);
  doc.text(`Applicant:  ${application.fullName}`, 70, boxTop + 50);
  doc.text(`Generated Date:  ${report.generatedAt.toDateString()}`, 70, boxTop + 75);
  doc.text(`Model Version:  ${prediction.modelVersion}`, 70, boxTop + 100);

  doc.image(qrBuffer, 390, boxTop, { width: 120 });
  doc.fontSize(8).fillColor(COLOR_MUTED).text('Scan to verify', 390, boxTop + 122, { width: 120, align: 'center' });

  doc.moveDown(12);
  doc.fontSize(9).fillColor(COLOR_MUTED).text(
    'This report is generated by an academic machine-learning decision-support system. It does not constitute an official bank approval or guaranteed lending decision.',
    { align: 'center' }
  );

  // ============ PAGE 2 — APPLICANT / EMPLOYMENT / FINANCIAL / LOAN ============
  doc.addPage();
  sectionHeading('Applicant Profile');
  kvRow('Full Name', application.fullName);
  kvRow('Age', application.age);
  kvRow('Gender', application.gender);
  kvRow('Marital Status', application.maritalStatus);
  kvRow('Education', application.education);
  kvRow('Residential Status', application.residentialStatus);
  doc.moveDown();
  sectionDivider();

  sectionHeading('Employment Information');
  kvRow('Employment Type', application.employmentType);
  kvRow('Occupation', application.occupation);
  kvRow('Years of Employment', application.yearsOfEmployment);
  kvRow('Self Employed', application.selfEmployed ? 'Yes' : 'No');
  doc.moveDown();
  sectionDivider();

  sectionHeading('Financial Information');
  kvRow('Annual Income', `₹${application.annualIncome.toLocaleString('en-IN')}`);
  kvRow('Monthly Income', `₹${Math.round(application.monthlyIncome).toLocaleString('en-IN')}`);
  kvRow('Monthly Expenses', `₹${application.monthlyExpenses.toLocaleString('en-IN')}`);
  kvRow('Existing EMI', `₹${(application.existingEMI || 0).toLocaleString('en-IN')}`);
  kvRow('Debt-to-Income Ratio', `${application.debtToIncomeRatio}%`);
  doc.moveDown();
  sectionDivider();

  sectionHeading('Loan Information');
  kvRow('Loan Amount', `₹${application.loanAmount.toLocaleString('en-IN')}`);
  kvRow('Loan Tenure', `${application.loanTenure} months`);
  kvRow('Loan Purpose', application.loanPurpose);
  kvRow('Credit History', application.creditHistory);

  // ============ PAGE 3 — AI MODEL ANALYSIS ============
  doc.addPage();
  doc.fontSize(15).fillColor(COLOR_PRIMARY).text('AI MODEL ANALYSIS');
  doc.moveDown();
  sectionDivider();

  kvRow('Prediction', prediction.prediction);
  kvRow('Estimated Probability', `${Math.round(prediction.probability * 100)}%`);
  kvRow('Model', prediction.modelName);
  kvRow('Model Version', prediction.modelVersion);
  doc.moveDown();
  doc.fontSize(9).fillColor(COLOR_MUTED).text(prediction.interpretation || '', { width: 495 });
  doc.moveDown();
  sectionDivider();

  sectionHeading('Important Factors (Explainable AI)');
  prediction.factors.forEach(f => {
    doc.fontSize(10).fillColor(COLOR_TEXT).text(
      `${f.impact === 'Negative' ? '⚠' : f.impact === 'Neutral' ? '•' : '✓'} ${f.name} — ${f.impact} contribution (${Math.round(f.contribution)}%)`
    );
  });
  doc.moveDown();
  doc.fontSize(8).fillColor(COLOR_MUTED).text(`Explanation method: ${prediction.explanationMethod}`);

  // ============ PAGE 4 — FINANCIAL HEALTH / RECOMMENDATION / DISCLAIMER ============
  doc.addPage();
  sectionHeading('Financial Health');
  kvRow('Income Stability', `${Math.round(prediction.financialHealth.incomeStability)}%`);
  kvRow('Loan Affordability', `${Math.round(prediction.financialHealth.loanAffordability)}%`);
  kvRow('Debt Burden', `${Math.round(prediction.financialHealth.debtBurden)}%`);
  doc.moveDown();
  sectionDivider();

  if (prediction.recommendation) {
    sectionHeading('AI Loan Recommendation');
    kvRow('Requested Loan', `₹${prediction.recommendation.requestedLoan.toLocaleString('en-IN')}`);
    kvRow('Recommended Range', `₹${prediction.recommendation.recommendedMin.toLocaleString('en-IN')} – ₹${prediction.recommendation.recommendedMax.toLocaleString('en-IN')}`);
    kvRow('Recommended Tenure', `${prediction.recommendation.recommendedTenure} months`);
    kvRow('Estimated EMI', `₹${prediction.recommendation.estimatedEMI.toLocaleString('en-IN')}/mo`);
    kvRow('Affordability', prediction.recommendation.affordability);
    doc.moveDown();
    sectionDivider();
  }

  sectionHeading('Disclaimer');
  doc.fontSize(9).fillColor(COLOR_MUTED).text(
    'This report presents the output of an academic machine-learning decision-support system. The prediction is a model-estimated probability, not a statistically calibrated confidence score, and does not represent a guaranteed loan approval or official lending decision by any financial institution. Financial indicators and recommendations shown are project-derived estimates for informational purposes only.',
    { width: 495 }
  );
  doc.moveDown();
  sectionDivider();

  kvRow('Report ID', report.reportId);
  kvRow('Report Hash', report.reportHash.substring(0, 32) + '...');
  kvRow('Generated Timestamp', report.generatedAt.toLocaleString('en-IN'));
  doc.moveDown();
  doc.fontSize(8).fillColor(COLOR_MUTED).text(`Verify this report at: ${verifyUrl}`, { align: 'center' });

  doc.end();
}

module.exports = { createReportRecord, generateReportPDF, generateReportHash };